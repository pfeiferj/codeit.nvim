vim.opt.runtimepath:prepend(vim.fn.getcwd())
local prompt_ui = require('codeit.tools.approval.prompt')
local tools = require('codeit.tools')
local root = vim.fn.getcwd()
local dir = vim.fn.tempname()
local other = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
vim.fn.mkdir(other, 'p')
vim.fn.writefile({ 'tracked secret' }, dir .. '/tracked.txt')
vim.fn.writefile({ 'untracked secret' }, dir .. '/untracked.txt')
vim.fn.writefile({ 'outside secret' }, other .. '/outside.txt')
assert(vim.fn.system({ 'git', '-C', dir, 'init', '-q' }) == '')
assert(vim.fn.system({ 'git', '-C', dir, 'add', 'tracked.txt' }) == '')
vim.uv.fs_symlink(other .. '/outside.txt', dir .. '/escape.txt')
vim.cmd.cd(dir)
local tracked = vim.fn.bufadd(dir .. '/tracked.txt')
vim.fn.bufload(tracked)
local untracked = vim.fn.bufadd(dir .. '/untracked.txt')
vim.fn.bufload(untracked)
local outside = vim.fn.bufadd(other .. '/outside.txt')
vim.fn.bufload(outside)

local function check(name, args, source, requires_approval)
  local prompted, result = false, nil
  prompt_ui.show = function(_, _, cb)
    prompted = true
    cb('reject')
  end
  vim.ui.input = function(_, cb) cb(nil) end
  tools.execute(name, args, source, function(value) result = value end, function() return true end)
  assert(vim.wait(5000, function() return result ~= nil end), 'timed out: ' .. name)
  assert(prompted == requires_approval, name .. ' ' .. vim.json.encode(args) .. ': unexpected approval prompt')
  if prompted then assert(result:find('Rejected by user', 1, true), result) end
  return result
end

local function policy(mode)
  tools.configure({ trusted_workspaces = mode and { [dir] = mode } or {} })
end

policy(nil)
check('read_file', { path = 'tracked.txt' }, nil, true)
check('read_source_buffer', {}, tracked, true)
check('git_diff', {}, nil, true)
check('list_workspace_files', {}, nil, true)
check('list_buffers', {}, nil, true)
policy('tracked')
assert(check('read_file', { path = 'tracked.txt' }, nil, false):find('tracked secret', 1, true))
check('read_file', { path = 'untracked.txt' }, nil, true)
check('read_file', { path = 'escape.txt' }, nil, true)
check('read_source_buffer', {}, tracked, false)
check('read_loaded_buffer', { buffer_id = untracked }, tracked, true)
check('read_loaded_buffer', { buffer_id = outside }, tracked, true)
check('list_buffers', {}, nil, true)
check('list_workspace_files', {}, nil, true)
check('search_workspace', { query = 'secret' }, nil, true)
check('get_diagnostics', {}, nil, true)
check('get_diagnostics', { path = '' }, nil, true)
check('get_diagnostics', { path = 'tracked.txt' }, nil, false)
check('get_diagnostics', { path = 'untracked.txt' }, nil, true)
check('git_status', {}, nil, true)
check('git_diff', {}, nil, false)
check('git_diff', { path = 'untracked.txt' }, nil, true)
policy('all')
check('read_file', { path = 'untracked.txt' }, nil, false)
tools.configure({ trusted_workspaces = { [dir] = 'all' }, validators = {
  function(name) if name == 'read_file' or name == 'list_buffers' then return 'ask' end end,
} })
check('read_file', { path = 'untracked.txt' }, nil, true)
check('list_buffers', {}, outside, true)
policy('all')
check('run_command', { argv = { 'echo', 'test' } }, nil, true)
check('read_file', { path = 'escape.txt' }, nil, true)
check('read_loaded_buffer', { buffer_id = outside }, tracked, true)
check('list_buffers', {}, nil, false)
check('list_buffers', { include_external = true }, nil, true)
check('list_buffers', {}, outside, false)
local unnamed = vim.api.nvim_create_buf(true, false)
check('list_buffers', {}, unnamed, false)
local unsaved = vim.fn.bufadd(dir .. '/unsaved.txt')
vim.fn.bufload(unsaved)
check('list_buffers', { include_external = false }, unsaved, false)
check('list_buffers', { include_external = true }, unnamed, true)
policy('tracked')
check('list_buffers', {}, unsaved, true)
policy('all')
check('search_workspace', { query = 'secret' }, nil, false)
check('get_diagnostics', {}, nil, false)
check('get_diagnostics', { path = '' }, nil, false)
check('git_status', {}, nil, false)
vim.api.nvim_buf_delete(outside, { force = true })
check('list_buffers', {}, nil, false)
local child = dir .. '/repo'
vim.fn.mkdir(child, 'p')
vim.fn.writefile({ 'child secret' }, child .. '/tracked.txt')
vim.fn.writefile({ 'child untracked' }, child .. '/untracked.txt')
assert(vim.fn.system({ 'git', '-C', child, 'init', '-q' }) == '')
assert(vim.fn.system({ 'git', '-C', child, 'add', 'tracked.txt' }) == '')
vim.cmd.cd(child)
policy('tracked')
check('read_file', { path = 'tracked.txt' }, nil, false)
check('read_file', { path = 'untracked.txt' }, nil, true)
policy('all')
check('read_file', { path = 'untracked.txt' }, nil, false)
assert(check('read_file', { path = '../tracked.txt' }, nil, false):find('tracked secret', 1, true))
check('read_loaded_buffer', { buffer_id = tracked }, nil, false)
-- Trust follows the target file, even while the current workspace is untrusted.
vim.cmd.cd(other)
assert(check('read_file', { path = dir .. '/untracked.txt' }, nil, false):find('untracked secret', 1, true))
check('read_loaded_buffer', { buffer_id = tracked }, nil, false)
check('read_source_buffer', {}, tracked, false)
check('list_workspace_files', {}, nil, true)
check('search_workspace', { query = 'secret' }, nil, true)
check('get_diagnostics', {}, nil, true)
local ns = vim.api.nvim_create_namespace('trusted-workspace-test')
vim.diagnostic.set(ns, tracked, { { lnum = 0, col = 0, message = 'external diagnostic' } })
assert(check('get_diagnostics', { path = dir .. '/tracked.txt' }, nil, false):find('external diagnostic', 1, true))
policy('tracked')
assert(check('read_file', { path = dir .. '/tracked.txt' }, nil, false):find('tracked secret', 1, true))
check('read_file', { path = dir .. '/untracked.txt' }, nil, true)
check('read_loaded_buffer', { buffer_id = untracked }, nil, true)
check('get_diagnostics', { path = dir .. '/untracked.txt' }, nil, true)
-- Tracked inheritance works across repositories, including nested directories.
vim.fn.mkdir(child .. '/nested', 'p')
vim.fn.writefile({ 'nested tracked' }, child .. '/nested/file.txt')
assert(vim.fn.system({ 'git', '-C', child, 'add', 'nested/file.txt' }) == '')
assert(check('read_file', { path = child .. '/nested/file.txt' }, nil, false):find('nested tracked', 1, true))
-- Symlinks use the destination's trust, not the current workspace's trust.
assert(vim.uv.fs_symlink(dir .. '/tracked.txt', other .. '/trusted-link.txt'))
assert(check('read_file', { path = 'trusted-link.txt' }, nil, false):find('tracked secret', 1, true))
tools.configure({ trusted_workspaces = { [other] = 'all', [dir] = 'tracked' } })
check('read_file', { path = dir .. '/untracked.txt' }, nil, true)
-- Explicit child overrides and saved revocations apply to individual files.
tools.configure({ trusted_workspaces = { [dir] = 'all', [child] = 'tracked' } })
check('read_file', { path = child .. '/untracked.txt' }, nil, true)
local approval = require('codeit.tools.approval')
assert(approval.set_workspace_trust(nil, child))
check('read_loaded_buffer', { buffer_id = vim.fn.bufnr(child .. '/tracked.txt') }, nil, true)
assert(approval.set_workspace_trust('all', child))
assert(check('read_file', { path = child .. '/untracked.txt' }, nil, false):find('child untracked', 1, true))
check('read_file', { path = 'outside.txt' }, nil, true)
vim.cmd.cd(root)
vim.fn.delete(dir, 'rf')
vim.fn.delete(other, 'rf')
print('codeit trusted workspace tests passed')
