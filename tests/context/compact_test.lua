vim.opt.runtimepath:prepend(vim.fn.getcwd())
local temp = vim.fn.tempname()
vim.fn.mkdir(temp .. '/one', 'p')
vim.fn.mkdir(temp .. '/two', 'p')
vim.fn.chdir(temp .. '/one')
local history = require('codeit.chat.storage')
local workspace = history.workspace()
local requests, callbacks = {}, {}
package.loaded['codeit.providers'] = {
  chat = function(config, messages, specs, callback)
    requests[#requests + 1] = { config = vim.deepcopy(config), messages = vim.deepcopy(messages), specs = specs }
    callbacks[#callbacks + 1] = callback
  end,
}
local plugin = require('codeit')
plugin.setup({ provider = 'openrouter', compaction = { manual_keep_turns = 0 } })
assert(vim.fn.exists(':CodeitCompact') == 2)
plugin.compact() -- empty chat
assert(#requests == 0)
plugin.send('first task' .. string.rep(' details', 30))
local chat_id = history.list(workspace)[1].id
plugin.compact() -- an unfinished turn
assert(#requests == 1)
callbacks[1]({ role = 'assistant', content = 'first answer' })
plugin.compact()
assert(#requests == 2 and #requests[2].specs == 0)
assert(requests[2].messages[2].content:find('first answer', 1, true))
plugin.send('blocked while compacting')
assert(#requests == 2 and #history.load(workspace, chat_id).messages == 3)
callbacks[2](nil, 'temporary error')
assert(history.load(workspace, chat_id).context_summary == nil)
plugin.compact()
callbacks[3]({ role = 'assistant', content = '  Project summary.  ' }, nil,
  { cost = 0.25, prompt_tokens = 100, completion_tokens = 20 })
local saved = history.load(workspace, chat_id)
assert(saved.context_summary == 'Project summary.' and saved.compacted_until == 3)
assert(saved.cost == 0.25 and saved.tokens_in == 100 and saved.tokens_out == 20)
assert(saved.turn_costs[1].cost == 0 and saved.turn_costs[1].missing_cost == 1,
  'manual compaction must not change an already completed turn cost')
assert(saved.cost_by_function.compaction.cost == 0.25 and saved.cost_by_function.compaction.requests == 1)
assert(not saved.turn_costs[1].cost_by_function.compaction)
assert(saved.context_tokens and saved.context_tokens > 0 and saved.context_estimated == true,
  'compaction must replace the stale context size with an estimate')
assert(vim.fn.exists(':CodeitContext') == 2)
plugin.open()
local chat_buf = vim.fn.bufnr('codeit://chat')
local function usage_line()
  return vim.api.nvim_buf_get_lines(chat_buf, 1, 2, false)[1]
end
assert(usage_line():find('Context: ~', 1, true))
plugin.context()
local ctx = vim.fn.bufnr('codeit://context')
local lines = vim.api.nvim_buf_get_lines(ctx, 0, -1, false)
local summary_row
for i, line in ipairs(lines) do
  if line == 'Project summary.' then summary_row = i - 1; break end
end
assert(summary_row and table.concat(lines, '\n'):find('You are a coding assistant operating inside Neovim', 1, true))
vim.api.nvim_buf_set_lines(ctx, 0, 1, false, { 'changed heading' })
assert(not pcall(vim.cmd, 'write'))
assert(history.load(workspace, chat_id).context_summary == 'Project summary.')
vim.api.nvim_buf_set_lines(ctx, 0, 1, false, { lines[1] })
vim.api.nvim_buf_set_lines(ctx, summary_row, summary_row + 1, false, { 'Edited summary.' })
vim.cmd('write')
assert(history.load(workspace, chat_id).context_summary == 'Edited summary.')
assert(usage_line():find('Context: ~', 1, true))
vim.cmd('close')
assert(#saved.messages == 3 and saved.messages[3].content == 'first answer')
plugin.compact()
assert(#requests == 3, 'already compacted turns must not be summarized again')
plugin.send('second task')
assert(#requests[4].messages == 3 and requests[4].messages[1].role == 'system')
assert(requests[4].messages[2].content:find('Edited summary.', 1, true))
assert(requests[4].messages[3].content == 'second task')
callbacks[4]({ role = 'assistant', content = 'second answer' }, nil,
  { total_tokens = 500, prompt_tokens = 450, completion_tokens = 50 })
assert(not usage_line():find('Context: ~', 1, true) and usage_line():find('Context: 0.5k', 1, true))
plugin.resume(chat_id)
plugin.send('third task')
assert(#requests[5].messages == 5)
assert(requests[5].messages[2].content:find('Edited summary.', 1, true))
assert(requests[5].messages[3].content == 'second task')
callbacks[5]({ role = 'assistant', content = 'third answer' })
plugin.compact()
assert(#requests[6].specs == 0)
assert(requests[6].messages[2].content:find('Edited summary.', 1, true))
assert(not requests[6].messages[2].content:find('first answer', 1, true), 'do not resend compacted turns')
assert(requests[6].messages[2].content:find('third answer', 1, true))
callbacks[6]({ role = 'assistant', content = 'Updated summary.' })
plugin.send('fourth task')
assert(#requests[7].messages == 3 and requests[7].messages[2].content:find('Updated summary.', 1, true))
callbacks[7]({ role = 'assistant', content = 'fourth answer' })
plugin.compact()
local stale = callbacks[8]
plugin.new()
stale({ role = 'assistant', content = 'stale summary' })
assert(history.load(workspace, chat_id).context_summary == 'Updated summary.')
plugin.send('fresh task')
assert(#requests[9].messages == 2 and requests[9].messages[2].content == 'fresh task')
plugin.new()
plugin.resume(chat_id)
plugin.send('after resume')
assert(requests[10].messages[2].content:find('Updated summary.', 1, true))
assert(requests[10].messages[3].content == 'fourth task')
vim.fn.chdir(temp .. '/two')
plugin.new()
plugin.send('different workspace')
assert(#requests[11].messages == 2)
vim.fn.delete(temp, 'rf')
print('codeit compaction tests passed')
